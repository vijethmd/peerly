// Meeting report: renders the transcript, participation and AI notes for one
// finished meeting, and keeps polling while the AI is still writing.

import { $, h, clear, toast, copyToClipboard, formatDuration } from './room/ui.js';
import { installErrorReporting } from './room/telemetry.js';

installErrorReporting();

const reportId = location.pathname.split('/').filter(Boolean).pop();
let current = null;
let pollTimer = null;
let searchTerm = '';
let paintedKey = null;
let lastAiStatus = null;
const entranceTimers = new WeakMap();

const fmtDate = (ts) =>
  new Date(ts).toLocaleString([], { weekday: 'short', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });

function offset(ts, startedAt) {
  const total = Math.max(0, Math.floor((ts - startedAt) / 1000));
  const h2 = Math.floor(total / 3600);
  const m = String(Math.floor((total % 3600) / 60)).padStart(2, '0');
  const s = String(total % 60).padStart(2, '0');
  return h2 ? `${h2}:${m}:${s}` : `${m}:${s}`;
}

function humanDuration(ms) {
  const seconds = Math.max(0, Math.round(ms / 1000));
  if (seconds < 60) return `${seconds} sec`;
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return `${minutes} min`;
  const hours = Math.floor(minutes / 60);
  return minutes % 60 ? `${hours} h ${minutes % 60} min` : `${hours} h`;
}

const compact = (value) => (value >= 10000 ? `${(value / 1000).toFixed(value >= 100000 ? 0 : 1)}K` : value.toLocaleString());

function showState({ title, message, actions = [] }) {
  const state = $('#reportState');
  clear(state);
  state.hidden = false;
  $('#reportContent').hidden = true;
  $('#reportActions').hidden = true;
  if (title) state.append(h('h1', { text: title }));
  state.append(h('p', { text: message }));
  if (actions.length) {
    const row = h('div', { class: 'state-actions' });
    for (const action of actions) {
      row.append(h('button', { class: 'btn btn-ghost btn-sm', type: 'button', text: action.label, onClick: action.onSelect }));
    }
    state.append(row);
  }
}

async function load() {
  try {
    const response = await fetch(`/api/report/${reportId}`);
    if (response.status === 404) {
      showState({
        title: 'These notes aren’t available',
        message: 'The link may be wrong, or the notes may have expired. Peerly keeps meeting notes for a limited time.'
      });
      return;
    }
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    current = await response.json();
    render(current);
  } catch {
    showState({
      title: 'Couldn’t load the notes',
      message: 'Something went wrong while loading this page.',
      actions: [{ label: 'Try again', onSelect: () => load() }]
    });
  }
}

function schedulePoll(report) {
  clearTimeout(pollTimer);
  const aiWorking = report.ai && (report.ai.status === 'waiting' || report.ai.status === 'running');
  if (report.status === 'recording') pollTimer = setTimeout(load, 10000);
  else if (aiWorking) pollTimer = setTimeout(load, 4000);
}

function render(report) {
  schedulePoll(report);

  if (report.status === 'recording') {
    showState({
      title: 'This meeting is still going',
      message: 'Notes, the transcript and AI summary appear here as soon as the meeting ends. You can keep this page open.'
    });
    return;
  }

  const content = $('#reportContent');
  const firstPaint = content.hidden;
  $('#reportState').hidden = true;
  content.hidden = false;
  $('#reportActions').hidden = false;

  const ai = report.ai || { status: 'disabled' };
  const data = ai.status === 'ready' ? ai.data : null;
  const { meeting } = report;

  document.title = `${data?.title || `Meeting ${meeting.roomId}`} - Peerly notes`;
  $('#reportTitle').textContent = data?.title || `Meeting ${meeting.roomId}`;
  $('#reportMeta').textContent = [
    fmtDate(meeting.startedAt),
    humanDuration(meeting.durationMs),
    `${report.participants.length} ${report.participants.length === 1 ? 'person' : 'people'}`,
    `code ${meeting.roomId}`
  ].join(' · ');

  renderAiBanner(ai);
  renderAi(data);

  // Only the AI part changes while we poll for the notes. Redrawing the rest
  // would also wipe whatever is being typed into the transcript search.
  const key = [report.status, report.transcript.length, report.chat.length, report.participants.length, report.timeline?.length || 0].join(':');
  if (key !== paintedKey) {
    paintedKey = key;
    renderStats(report);
    renderParticipation(report);
    renderTimeline(report);
    renderTranscript(report);
    renderChat(report);
  }

  if (firstPaint) playEntrance(content);
  else if (ai.status !== lastAiStatus) playEntrance($('#aiSection'));
  lastAiStatus = ai.status;

  const expires = report.expiresAt ? ` Available until ${fmtDate(report.expiresAt)}.` : '';
  $('#reportFooter').textContent = `Notes generated by Peerly.${expires} Private messages are never included.`;
}

// Staggered rise-in for the blocks under root. The class comes off again
// afterwards so blocks redrawn by later polls don't replay it.
function playEntrance(root) {
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  root.querySelectorAll('.stat-tile').forEach((el, i) => el.style.setProperty('--i', i));
  root.querySelectorAll('.report-card:not([hidden])').forEach((el, i) => el.style.setProperty('--i', i));
  root.classList.remove('is-entering');
  void root.offsetWidth;
  root.classList.add('is-entering');
  clearTimeout(entranceTimers.get(root));
  entranceTimers.set(root, setTimeout(() => root.classList.remove('is-entering'), 2600));
}

function renderAiBanner(ai) {
  const banner = $('#aiBanner');
  clear(banner);
  banner.hidden = false;
  banner.className = 'report-banner';

  if (ai.status === 'waiting' || ai.status === 'running') {
    banner.classList.add('report-banner-working');
    banner.append(
      h('div', { class: 'spinner' }),
      h('div', { class: 'report-banner-body' },
        h('strong', { text: 'Writing your meeting notes' }),
        'The AI is reading the transcript. This page updates on its own.')
    );
    return;
  }
  if (ai.status === 'failed') {
    banner.classList.add('report-banner-error');
    const body = h('div', { class: 'report-banner-body' }, h('strong', { text: 'AI notes couldn’t be generated' }), ai.error || '');
    banner.append(body);
    if (ai.retryable) {
      banner.append(
        h('button', {
          class: 'mini-btn',
          type: 'button',
          text: 'Try again',
          onClick: async (event) => {
            event.currentTarget.disabled = true;
            const response = await fetch(`/api/report/${reportId}/retry`, { method: 'POST' });
            if (response.ok) setTimeout(load, 1000);
            else toast('Could not start the AI again right now.', { tone: 'error' });
          }
        })
      );
    }
    return;
  }
  if (ai.status === 'disabled') {
    banner.append(
      h('div', { class: 'report-banner-body' },
        h('strong', { text: 'AI notes are switched off on this server' }),
        'The full transcript and meeting statistics are below.')
    );
    return;
  }
  if (ai.status === 'skipped') {
    banner.append(h('div', { class: 'report-banner-body' }, h('strong', { text: 'No AI summary' }), ai.error || ''));
    return;
  }
  banner.hidden = true;
}

function renderStats(report) {
  const row = $('#statTiles');
  clear(row);
  const words = report.participants.reduce((sum, p) => sum + (p.words || 0), 0);
  const reactions = Object.values(report.reactions?.totals || {}).reduce((sum, count) => sum + count, 0);
  const messages = report.chat.length;

  const tiles = [
    { label: 'Length', value: humanDuration(report.meeting.durationMs) },
    { label: 'People', value: String(report.participants.length) },
    { label: 'Words spoken', value: compact(words), sub: `${report.transcript.length} transcript lines` },
    { label: 'Messages', value: String(messages) },
    { label: 'Reactions', value: String(reactions) }
  ];
  for (const tile of tiles) {
    row.append(
      h('div', { class: 'stat-tile' },
        h('p', { class: 'stat-label', text: tile.label }),
        h('p', { class: 'stat-value', text: tile.value }),
        tile.sub ? h('p', { class: 'stat-sub', text: tile.sub }) : null)
    );
  }
}

function card(title, count) {
  const section = h('section', { class: 'report-card' });
  const heading = h('h2', { text: title });
  if (count !== undefined) heading.append(h('span', { class: 'count', text: ` (${count})` }));
  section.append(heading);
  return section;
}

function listCard(title, items, className = '') {
  const section = card(title);
  const list = h('ul', { class: `report-list ${className}`.trim() });
  for (const item of items) list.append(h('li', { text: item }));
  section.append(list);
  return section;
}

function renderAi(data) {
  const container = $('#aiSection');
  clear(container);
  if (!data) return;

  if (data.summary) {
    const section = card('Summary');
    section.append(h('p', { class: 'report-summary', text: data.summary }));
    container.append(section);
  }
  if (data.keyPoints?.length) container.append(listCard('Key points', data.keyPoints));
  if (data.decisions?.length) container.append(listCard('Decisions', data.decisions, 'decisions'));

  if (data.actionItems?.length) {
    const section = card('Action items', data.actionItems.length);
    const list = h('ul', { class: 'action-items' });
    data.actionItems.forEach((item, index) => {
      const checkbox = h('input', { type: 'checkbox', id: `action-${index}`, 'aria-label': `Mark done: ${item.task}` });
      const row = h('li', { class: 'action-item' });
      checkbox.addEventListener('change', () => row.classList.toggle('done', checkbox.checked));
      const tags = h('div', { class: 'action-tags' });
      if (item.owner) tags.append(h('span', { class: 'tag', text: item.owner }));
      if (item.due) tags.append(h('span', { class: 'tag', text: item.due }));
      row.append(
        checkbox,
        h('div', { class: 'action-body' },
          h('label', { class: 'action-task', for: `action-${index}`, text: item.task }),
          tags.childElementCount ? tags : null)
      );
      list.append(row);
    });
    section.append(list);
    container.append(section);
  }

  if (data.openQuestions?.length) container.append(listCard('Open questions', data.openQuestions, 'questions'));

  if (data.topics?.length) {
    const section = card('How the meeting went');
    const topics = h('div', { class: 'topics' });
    for (const topic of data.topics) {
      topics.append(
        h('div', { class: 'topic' },
          h('span', { class: 'topic-time', text: topic.start || '' }),
          h('div', {}, h('h3', { text: topic.title }), h('p', { text: topic.summary })))
      );
    }
    section.append(topics);
    container.append(section);
  }
}

function renderParticipation(report) {
  const section = $('#participationSection');
  clear(section);
  const participants = [...report.participants];
  if (!participants.length) {
    section.hidden = true;
    return;
  }
  section.hidden = false;
  section.append(h('h2', { text: 'Who spoke' }));

  const totalTalk = participants.reduce((sum, p) => sum + (p.talkMs || 0), 0);
  const totalWords = participants.reduce((sum, p) => sum + (p.words || 0), 0);
  const useTalk = totalTalk > 0;
  const total = useTalk ? totalTalk : totalWords;

  const bars = h('div', { class: 'bars' });
  participants
    .sort((a, b) => (useTalk ? b.talkMs - a.talkMs : b.words - a.words))
    .forEach((participant) => {
      const value = useTalk ? participant.talkMs || 0 : participant.words || 0;
      const share = total ? Math.round((value / total) * 100) : 0;
      const name = h('div', { class: 'bar-name', text: participant.name });
      if (participant.wasHost) name.append(h('span', { class: 'tag', text: 'host' }));
      const fill = h('div', { class: 'bar-fill' });
      fill.style.setProperty('--value', `${Math.max(share, value > 0 ? 1 : 0)}%`);
      const label = useTalk ? `${share}% · ${formatDuration(participant.talkMs)}` : `${share}% · ${participant.words} words`;
      bars.append(
        h('div', {
          class: 'bar-row',
          title: `${participant.name}: ${formatDuration(participant.talkMs)} speaking, ${participant.words} words, ${participant.messages} messages, ${formatDuration(participant.presentMs)} in the meeting`
        },
          name,
          h('div', { class: 'bar-track' }, fill),
          h('div', { class: 'bar-value', text: label })
        )
      );
    });
  section.append(bars);
  section.append(
    h('p', {
      class: 'bars-note',
      text: useTalk
        ? 'Share of speaking time measured from each person’s microphone.'
        : 'No speaking time was measured, so this shows the share of transcribed words.'
    })
  );

  const reactions = Object.entries(report.reactions?.totals || {}).sort((a, b) => b[1] - a[1]);
  if (reactions.length) {
    const totals = h('div', { class: 'reaction-totals' });
    for (const [emoji, count] of reactions) {
      totals.append(h('div', { class: 'reaction-total' }, emoji, h('span', { text: String(count) })));
    }
    section.append(h('h2', { text: 'Reactions' }), totals);
    const moments = report.reactions?.moments || [];
    if (moments.length) {
      const list = h('ul', { class: 'report-list' });
      for (const moment of moments) {
        list.append(
          h('li', {
            text: `${offset(moment.ts, report.meeting.startedAt)} — ${moment.count} reactions at once, mostly ${moment.emoji}`
          })
        );
      }
      section.append(list);
    }
  }
}

const TIMELINE_TEXT = {
  join: (event) => [event.name, ' joined'],
  leave: (event) => [event.name, event.reason === 'removed' ? ' was removed' : ' left'],
  'share-start': (event) => [event.name, ' started presenting'],
  'share-stop': (event) => [event.name, ' stopped presenting'],
  'transcription-on': (event) => [event.name, ' started the transcript'],
  'transcription-off': (event) => [event.name, ' stopped the transcript'],
  host: (event) => [event.name, ' became the host'],
  ended: (event) => [event.name, ' ended the meeting']
};

function renderTimeline(report) {
  const section = $('#timelineSection');
  clear(section);
  const events = report.timeline || [];
  if (!events.length) {
    section.hidden = true;
    return;
  }
  section.hidden = false;
  section.append(h('h2', { text: 'Timeline' }));
  const list = h('ul', { class: 'timeline' });
  for (const event of events) {
    const describe = TIMELINE_TEXT[event.type];
    if (!describe) continue;
    const [name, rest] = describe(event);
    list.append(
      h('li', {},
        h('span', { class: 'timeline-time', text: offset(event.ts, report.meeting.startedAt) }),
        h('span', { class: 'timeline-dot' }),
        h('span', { class: 'timeline-text' }, h('strong', { text: name || 'Someone' }), rest))
    );
  }
  section.append(list);
}

function renderTranscript(report) {
  const section = $('#transcriptSection');
  clear(section);
  if (!report.transcript.length) {
    section.hidden = true;
    return;
  }
  section.hidden = false;
  section.append(h('h2', { text: 'Transcript' }));

  const search = h('input', {
    class: 'transcript-search',
    type: 'search',
    placeholder: 'Search the transcript',
    'aria-label': 'Search the transcript',
    value: searchTerm
  });
  const copyBtn = h('button', {
    class: 'mini-btn',
    type: 'button',
    text: 'Copy transcript',
    onClick: async () => {
      const ok = await copyToClipboard(transcriptText(report));
      toast(ok ? 'Transcript copied' : 'Could not copy the transcript', { tone: ok ? 'info' : 'error' });
    }
  });
  section.append(h('div', { class: 'transcript-controls' }, search, copyBtn));

  const list = h('div', { class: 'report-transcript' });
  section.append(list);
  const draw = () => renderTurns(list, report, searchTerm);
  search.addEventListener('input', () => {
    searchTerm = search.value.trim();
    draw();
  });
  draw();

  if (report.meeting.transcriptTruncated) {
    section.append(h('p', { class: 'bars-note', text: 'This meeting was long enough to hit the transcript size limit, so the end is missing.' }));
  }
}

// Merge consecutive lines from the same speaker into one readable turn.
function turnsOf(transcript) {
  const turns = [];
  for (const segment of transcript) {
    const last = turns[turns.length - 1];
    if (last && last.name === segment.name && segment.ts - last.lastTs < 30000) {
      last.text += ` ${segment.text}`;
      last.lastTs = segment.ts;
    } else {
      turns.push({ name: segment.name, ts: segment.ts, lastTs: segment.ts, text: segment.text });
    }
  }
  return turns;
}

function renderTurns(container, report, term) {
  clear(container);
  const needle = term.toLowerCase();
  const turns = turnsOf(report.transcript).filter(
    (turn) => !needle || turn.text.toLowerCase().includes(needle) || turn.name.toLowerCase().includes(needle)
  );
  if (!turns.length) {
    container.append(h('p', { class: 'empty-note', text: 'Nothing matches that search.' }));
    return;
  }
  for (const turn of turns) {
    const text = h('p', { class: 'turn-text' });
    text.append(h('span', { class: 'turn-speaker', text: `${turn.name}:` }));
    if (needle) {
      // Highlight matches without ever treating the text as markup.
      let rest = turn.text;
      let index = rest.toLowerCase().indexOf(needle);
      while (index >= 0) {
        text.append(document.createTextNode(rest.slice(0, index)));
        text.append(h('mark', { text: rest.slice(index, index + needle.length) }));
        rest = rest.slice(index + needle.length);
        index = rest.toLowerCase().indexOf(needle);
      }
      text.append(document.createTextNode(rest));
    } else {
      text.append(document.createTextNode(turn.text));
    }
    container.append(
      h('div', { class: 'turn' }, h('span', { class: 'turn-time', text: offset(turn.ts, report.meeting.startedAt) }), text)
    );
  }
}

function renderChat(report) {
  const section = $('#chatSection');
  clear(section);
  if (!report.chat.length) {
    section.hidden = true;
    return;
  }
  section.hidden = false;
  section.append(h('h2', { text: 'Messages' }, h('span', { class: 'count', text: ` (${report.chat.length})` })));
  const list = h('div', { class: 'report-transcript' });
  for (const message of report.chat) {
    list.append(
      h('div', { class: 'turn' },
        h('span', { class: 'turn-time', text: offset(message.ts, report.meeting.startedAt) }),
        h('p', { class: 'turn-text' }, h('span', { class: 'turn-speaker', text: `${message.name}:` }), message.text))
    );
  }
  section.append(list);
}

function transcriptText(report) {
  return turnsOf(report.transcript)
    .map((turn) => `[${offset(turn.ts, report.meeting.startedAt)}] ${turn.name}: ${turn.text}`)
    .join('\n');
}

function toMarkdown(report) {
  const data = report.ai?.status === 'ready' ? report.ai.data : null;
  const lines = [`# ${data?.title || `Meeting ${report.meeting.roomId}`}`, ''];
  lines.push(
    `${fmtDate(report.meeting.startedAt)} · ${humanDuration(report.meeting.durationMs)} · ${report.participants.length} people · code ${report.meeting.roomId}`,
    ''
  );
  if (data) {
    if (data.summary) lines.push('## Summary', '', data.summary, '');
    if (data.keyPoints?.length) lines.push('## Key points', '', ...data.keyPoints.map((point) => `- ${point}`), '');
    if (data.decisions?.length) lines.push('## Decisions', '', ...data.decisions.map((item) => `- ${item}`), '');
    if (data.actionItems?.length) {
      lines.push('## Action items', '');
      for (const item of data.actionItems) {
        const details = [item.owner, item.due].filter(Boolean).join(', ');
        lines.push(`- [ ] ${item.task}${details ? ` (${details})` : ''}`);
      }
      lines.push('');
    }
    if (data.openQuestions?.length) lines.push('## Open questions', '', ...data.openQuestions.map((item) => `- ${item}`), '');
    if (data.topics?.length) {
      lines.push('## How the meeting went', '');
      for (const topic of data.topics) lines.push(`- **${topic.start} ${topic.title}** — ${topic.summary}`);
      lines.push('');
    }
  }
  lines.push('## Who spoke', '');
  for (const participant of report.participants) {
    lines.push(
      `- ${participant.name}${participant.wasHost ? ' (host)' : ''}: ${formatDuration(participant.talkMs)} speaking, ${participant.words} words, ${participant.messages} messages`
    );
  }
  lines.push('', '## Transcript', '', transcriptText(report));
  if (report.chat.length) {
    lines.push('', '## Messages', '');
    for (const message of report.chat) {
      lines.push(`[${offset(message.ts, report.meeting.startedAt)}] ${message.name}: ${message.text}`);
    }
  }
  return lines.join('\n');
}

$('#copyLinkBtn').addEventListener('click', async () => {
  const ok = await copyToClipboard(location.href);
  toast(ok ? 'Link copied' : location.href);
});
$('#printBtn').addEventListener('click', () => window.print());
$('#downloadBtn').addEventListener('click', () => {
  if (!current) return;
  const blob = new Blob([toMarkdown(current)], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = h('a', { href: url, download: `peerly-notes-${current.meeting.roomId}.md` });
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10000);
});

